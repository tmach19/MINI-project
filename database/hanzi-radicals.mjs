const SUFFIX_CHARS = new Set([
  '子', '头', '儿', '们', '的', '了', '着', '过', '吗', '呢', '吧', '啊',
  '个', '么', '了',
]);

export function cleanVocabChars(hanzi) {
  const cleaned = String(hanzi || '')
    .replace(/[（(][^）)]*[)）]/g, '')
    .split('/')[0];
  return Array.from(cleaned).filter((ch) => /[\u4e00-\u9fff]/.test(ch));
}

export function getPrimaryCharForWord(hanzi) {
  const chars = cleanVocabChars(hanzi);
  if (chars.length === 0) return null;
  if (chars.length === 1) return chars[0];
  const meaningful = chars.find((ch) => !SUFFIX_CHARS.has(ch));
  return meaningful || chars[0];
}

export function getPrimaryRadicalForWord(hanzi) {
  const ch = getPrimaryCharForWord(hanzi);
  if (!ch) return null;
  const info = CHAR_MAP[ch];
  if (!info) return null;
  return RADICALS[info.r] || null;
}

export function getRadicalsInWord(hanzi) {
  const chars = cleanVocabChars(hanzi);
  const set = new Set();
  for (const ch of chars) {
    const info = CHAR_MAP[ch];
    if (info && RADICALS[info.r]) {
      set.add(RADICALS[info.r]);
    }
  }
  return Array.from(set);
}

export function buildVocabRadicalData(vocab) {
  const chars = cleanVocabChars(vocab.hanzi);
  if (chars.length === 0) return null;

  const primaryRadical = getPrimaryRadicalForWord(vocab.hanzi);
  if (!primaryRadical) return null;

  const breakdownParts = chars.map((ch) => {
    const info = CHAR_MAP[ch];
    if (!info) return `${ch}`;
    if (chars.length === 1) {
      return info.d;
    }
    return `${ch}: ${info.d}`;
  });
  const breakdown =
    chars.length === 1
      ? `${chars[0]} = ${breakdownParts[0]}.`
      : breakdownParts.join(' • ');

  const isGenericMnemonic =
    !vocab.mnemonic ||
    vocab.mnemonic.includes('Thành phần biểu ý/biểu âm cơ bản') ||
    vocab.mnemonic.includes('Kết hợp các thành tố [');

  let mnemonic = vocab.mnemonic;
  if (isGenericMnemonic) {
    const radShort = primaryRadical.split(') (')[0] + ')';
    const meaningClean = String(vocab.meaning || '').replace(/^\[[^\]]+\]\s*/, '').trim();
    if (chars.length === 1) {
      const info = CHAR_MAP[chars[0]];
      mnemonic = `Chữ ${chars[0]} (${vocab.pinyin}) mang nghĩa "${meaningClean}", bộ chính ${radShort}; cấu tạo: ${info.d}.`;
    } else {
      const summary = chars
        .map((c) => {
          const ci = CHAR_MAP[c];
          return ci ? `${c} [bộ ${ci.r}]` : c;
        })
        .join(' + ');
      mnemonic = `Ghép ${summary} để nhớ từ ${vocab.hanzi} (${vocab.pinyin}): "${meaningClean}".`;
    }
  }

  return {
    radical: primaryRadical,
    breakdown,
    mnemonic,
  };
}
